// RecordConsumeLog persists one settled consumption record and its normalized token breakdown.
func RecordConsumeLog(c *gin.Context, userId int, params RecordConsumeLogParams) {
	if !common.LogConsumeEnabled {
		return
	}
	logger.LogInfo(c, fmt.Sprintf(
		"record consume log: user_id=%d channel_id=%d model=%s quota=%d stream=%t duration_seconds=%d",
		userId,
		params.ChannelId,
		params.ModelName,
		params.Quota,
		params.IsStream,
		params.UseTimeSeconds,
	))
	username := c.GetString("username")
	requestId := c.GetString(common.RequestIdKey)
	upstreamRequestId := c.GetString(common.UpstreamRequestIdKey)
	createdAt := common.GetTimestamp()
	otherStr := common.MapToJsonStr(params.Other)
	inputTokens := params.PromptTokens
	if params.InputTokens != nil {
		// 使用计费阶段归一化后的常规输入，避免缓存 Token 在汇总时重复计算。
		inputTokens = *params.InputTokens
	}
	// 判断是否需要记录 IP
	needRecordIp := false
	if settingMap, err := GetUserSetting(userId, false); err == nil {
		if settingMap.RecordIpLog {
			needRecordIp = true
		}
	}
	log := &Log{
		UserId:              userId,
		Username:            username,
		CreatedAt:           createdAt,
		Type:                LogTypeConsume,
		Content:             params.Content,
		PromptTokens:        params.PromptTokens,
		CompletionTokens:    params.CompletionTokens,
		InputTokens:         inputTokens,
		CacheCreationTokens: params.CacheCreationTokens,
		CacheReadTokens:     params.CacheReadTokens,
		TokenName:           params.TokenName,
		ModelName:           params.ModelName,
		Quota:               params.Quota,
		ChannelId:           params.ChannelId,
		TokenId:             params.TokenId,
		UseTime:             params.UseTimeSeconds,
		IsStream:            params.IsStream,
		Group:               params.Group,
		Ip: func() string {
			if needRecordIp {
				return c.ClientIP()
			}
			return ""
		}(),
		RequestId:         requestId,
		UpstreamRequestId: upstreamRequestId,
		Other:             otherStr,
	}
	err := createLog(log)
	if err != nil {
		logger.LogError(c, common.LogText("failed to record log: %s", err.Error()))
	}
	if common.DataExportEnabled {
		LogQuotaData(QuotaDataLogParams{
			UserID:    userId,
			Username:  username,
			ModelName: params.ModelName,
			Quota:     params.Quota,
			CreatedAt: createdAt,
			TokenUsed: params.PromptTokens + params.CompletionTokens,
			UseGroup:  params.Group,
			TokenID:   params.TokenId,
			ChannelID: params.ChannelId,
			NodeName:  common.NodeName,
		})
	}
}

